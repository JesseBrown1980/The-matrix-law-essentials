#!/usr/bin/env python3
"""Exact carry-free signed two-channel packed-lane matrix action.

For every source vector v, emit v+ and v- as two nonnegative packed
integer vectors. Accumulate both channels by target with raw integer
edge multiplicities (and source shards merged first), then subtract
their independently unpacked entries. Supports the sign-changing
Krylov vectors generated by D-T Hamiltonians.

Proof: each target's incoming T row sum <= 72; if |v| <= M
then EACH channel's every digit <= 72*M. A word width w satisfying
2^w > 72*M forbids cross-lane carry. Whole-target W Gram uses the
signed difference, never the individual channels separately.
"""
from hashlib import sha256

COLS=8
ROW_CAP=72
SOURCE_COUNT=6
M=251


def need(ok,reason):
    if not ok:
        raise ValueError("SIGNED_PACKING_REFUSE_"+reason)


def emit(label,**fields):
    print(label+"|"+"|".join(str(k)+"="+str(v) for k,v in fields.items())+
          "|json=0",flush=True)


def pack_nonnegative(v,width):
    need(len(v)==COLS,"bad_lane_count")
    limit=1<<width
    need(all(0<=a<limit for a in v),"unsigned_lane_not_bounded")
    return sum(a<<(width*i) for i,a in enumerate(v))


def pack_signed(v,width):
    need(len(v)==COLS,"signed_lane_count")
    return (
        pack_nonnegative([max(x,0) for x in v],width),
        pack_nonnegative([max(-x,0) for x in v],width),
    )


def unpack_nonnegative(word,width):
    need(word>=0 and word<(1<<(COLS*width)),
         "packed_word_outside_allocated_lanes")
    mask=(1<<width)-1
    return tuple((word>>(width*j))&mask for j in range(COLS))


def choose_width(max_abs,bound=ROW_CAP):
    need(max_abs>=0 and bound>=0,"invalid_maximum")
    return (bound*max_abs).bit_length()+1


def target_reduce(vectors,records,width):
    """records are (destination index, source index, reverse coefficient).
    Return exact signed vectors for every target, never partial Gram.
    """
    limit=1<<width
    observed_max=max(abs(x) for row in vectors for x in row)
    need(limit>ROW_CAP*observed_max,
         "WIDTH_DOES_NOT_CERTIFY_INCOMING_BOUND")
    positive={}
    negative={}
    count={}
    for target,source,coefficient in records:
        need(0<=source<len(vectors) and 1<=coefficient<=ROW_CAP,
             "invalid_weighted_electric_edge")
        count[target]=count.get(target,0)+coefficient
        need(count[target]<=ROW_CAP,
             "incoming_row_sum_exceeds_72")
        a,b=pack_signed(vectors[source],width)
        positive[target]=positive.get(target,0)+coefficient*a
        negative[target]=negative.get(target,0)+coefficient*b
    out={}
    for target in positive:
        plus=unpack_nonnegative(positive[target],width)
        minus=unpack_nonnegative(negative[target],width)
        # Independent verified source global bound prevents overflow
        # even in intermediate lanes, before this unpack.
        need(max(plus)<limit and max(minus)<limit,
             "lane_capacity")
        out[target]=tuple(plus[i]-minus[i] for i in range(COLS))
    return out


def independent_scalar(vectors,records):
    sums={}
    count={}
    for target,source,coeff in records:
        if target not in sums:
            sums[target]=[0]*COLS
        count[target]=count.get(target,0)+coeff
        need(count[target]<=ROW_CAP,"scalar_row_cap")
        for k in range(COLS):
            sums[target][k]+=coeff*vectors[source][k]
    return {k:tuple(v) for k,v in sums.items()}


def W_gram(reduced,W):
    G=[[0]*COLS for _ in range(COLS)]
    for target,value in reduced.items():
        w=W[target]
        for i in range(COLS):
            for j in range(COLS):
                G[i][j]+=w*value[i]*value[j]
    return tuple(tuple(row) for row in G)


def run():
    src=tuple(tuple(
        (1 if (i+k)%2==0 else -1)*(1+(i*37+k*13)%M)
        for k in range(COLS)) for i in range(SOURCE_COUNT))
    largest=max(abs(v) for row in src for v in row)
    width=choose_width(largest)
    # Interleaved records as if originating from source-sharded
    # exact raw electric moves: multiple origins feed same target.
    records=(
        (111,0,5),(222,3,6),(111,1,7),(111,2,3),
        (222,4,9),(333,0,2),(111,4,8),(333,5,10),
        (222,1,5),(333,2,3),(111,5,2),(222,0,4),
    )
    for target in (111,222,333):
        total=sum(coef for dest,_,coef in records if dest==target)
        need(0<total<=ROW_CAP,"test_weighted_row_bound")
    known_W={111:6,222:3,333:2}
    packed=target_reduce(src,records,width)
    scalar=independent_scalar(src,records)
    need(packed==scalar,"signed_packing_not_equal_independent_scalar")
    Gpacked=W_gram(packed,known_W)
    Gscalar=W_gram(scalar,known_W)
    need(Gpacked==Gscalar,"signed_W_Gram_changed")
    # Both individual signed channels must be merged BEFORE squaring.
    wrong={}
    for target,source,coefficient in records:
        val=tuple(coefficient*x for x in src[source])
        part=W_gram({target:val},known_W)
        if not wrong:
            wrong=[[0]*COLS for _ in range(COLS)]
        for i in range(COLS):
            for j in range(COLS):
                wrong[i][j]+=part[i][j]
    need(tuple(tuple(row) for row in wrong)!=Gpacked,
         "cross_shard_Gram_missing")
    # Artificially narrow width is REFUSED by the proved interval
    # bound, rather than masked by an apparently valid packed word.
    too_narrow=(ROW_CAP*largest).bit_length()-1
    need(not ((1<<too_narrow)>ROW_CAP*largest),
         "narrow_width_not_rejected")
    bad_width_refused=False
    try:
        target_reduce(src,records,too_narrow)
    except ValueError:
        bad_width_refused=True
    need(bad_width_refused,"bad_width_passed")
    # Flip sign in a source but reuse old packed material: exact
    # independent scalar comparison must reject.
    changed=[list(v) for v in src]
    changed[1][2]=-changed[1][2]
    need(independent_scalar(changed,records)!=packed,
         "changed_source_sign_accepted")
    # Bad edge count can be self-consistent numerically but must
    # REFUSE the incoming 72-move bound before producing a Gram.
    over=((777,0,40),(777,1,33))
    over_refused=False
    try:
        target_reduce(src,over,width)
    except ValueError:
        over_refused=True
    need(over_refused,"overcomplete_target_row_accepted")
    fingerprint=sha256("|".join(
        str(x) for row in Gpacked for x in row).encode("ascii")).hexdigest()
    emit("SIGNED_PACKED_LANES_VERDICT",
         columns=COLS,weighted_row_max=ROW_CAP,
         signed_source_max_abs=largest,
         width=width,guaranteed_bound=ROW_CAP*largest,
         two_nonnegative_channels="PASS",
         independent_scalar_agreement="PASS",
         weighted_Gram="PASS",
         cross_shard_square_before_merge="REJECTED",
         false_lane_width="REFUSED",
         wrong_source_sign="DETECTED",
         over_72_target_incoming="REFUSED",
         exact_Gram_sha256=fingerprint,
         finite_3x4_actual_mu3="NOT_COMPUTED",
         Wilson_weight="HOLD")


if __name__=="__main__":
    run()
